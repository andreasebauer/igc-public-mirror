@register_runner("adapter.scout_level.verify_independent")
def verify_stage(*, controller, plan, stage, work_dir, run_dir):
    from .scout_l16 import _dependency_artifact
    _assert_conveyor_specs(stage["params"])
    fixture = controller.datasets.materialize(stage["params"]["fixture_dataset_sha256"], work_dir / "fixture_replay")
    sources = load_fixture_sources(fixture)
    prim = load_fixture_primitive(fixture)
    # Independent monolithic recomputation of generation + lane selection.
    merged = compute_generation_chunk(sources, prim)
    iwide, irelation, ilanes = exact_select_from_merged(merged, [x["sha256"] for x in sources], int(stage["params"]["per_lane"]))
    pwide = _dependency_artifact(controller, run_dir, "wide", "SCOUT_LEVEL_WIDE_RESULT.json", work_dir / "inputs/SCOUT_LEVEL_WIDE_RESULT.json")
    prel = _dependency_artifact(controller, run_dir, "wide", "SELECTED_RELATION.json", work_dir / "inputs/SELECTED_RELATION.json")
    planes = _dependency_artifact(controller, run_dir, "wide", "SEALED_LANE_SELECTION.json", work_dir / "inputs/SEALED_LANE_SELECTION.json")
    pcl = _dependency_artifact(controller, run_dir, "classify", "SCOUT_LEVEL_CLASSIFICATION.json", work_dir / "inputs/SCOUT_LEVEL_CLASSIFICATION.json")
    wide = json.loads(pwide.read_text(encoding="utf-8"))
    relation = json.loads(prel.read_text(encoding="utf-8"))
    lanes = json.loads(planes.read_text(encoding="utf-8"))
    classification = json.loads(pcl.read_text(encoding="utf-8"))
    prod_projection = {"generation": wide["generation"], "selection": wide["selection"], "bounded_relation": wide["bounded_relation"]}
    indep_projection = {"generation": iwide["generation"], "selection": iwide["selection"], "bounded_relation": iwide["bounded_relation"]}
    comparisons = {
        "wide_science_projection": canonical_sha256(prod_projection) == canonical_sha256(indep_projection),
        "selected_relation": canonical_sha256(relation) == canonical_sha256(irelation),
        "sealed_lanes": canonical_sha256({k: v for k, v in lanes.items() if k != "schema_id"}) == canonical_sha256({k: v for k, v in ilanes.items() if k != "schema_id"}),
        "classification_defined": classification.get("classification_defined") is True,
        "authority_reconnaissance_only": classification.get("authority") == "RECONNAISSANCE_ONLY",
    }
    status = "PASS" if all(comparisons.values()) else "FAIL"
    verification = {"schema_id": "IG_SCOUT_GENERIC_LEVEL_TERMINAL_VERIFICATION_V0_1", "status": status, "source_level": int(stage["params"]["source_level"]), "level": int(stage["params"]["target_level"]), "comparisons": comparisons, "independent_recomputation": "MONOLITHIC_EXACT_D_B_S_O_L", "historical_golden_used": False}
    p = work_dir / "SCOUT_LEVEL_TERMINAL_VERIFICATION.json"
    write_json_atomic(p, verification)
    if status != "PASS":
        raise RuntimeError(f"generic Scout independent verification failed: {comparisons}")
    return {"outputs": {"SCOUT_LEVEL_TERMINAL_VERIFICATION.json": p}, "stage_result": verification}
