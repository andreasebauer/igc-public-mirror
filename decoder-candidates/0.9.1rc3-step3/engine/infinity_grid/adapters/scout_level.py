def _resource_json(name: str) -> dict[str, Any]:
    p = files("infinity_grid").joinpath("resources/conveyor").joinpath(name)
    return json.loads(p.read_text(encoding="utf-8"))


def _spec_sha(name: str) -> str:
    obj = _resource_json(name)
    return canonical_sha256({k: v for k, v in obj.items() if k != "spec_sha256"})


def _assert_conveyor_specs(params: dict[str, Any]) -> None:
    expected = {
        "selection_rules_sha256": _spec_sha("SCOUT_CONVEYOR_SELECTION_RULES_v0.1.json"),
        "observer_sha256": _spec_sha("SCOUT_CONVEYOR_GENERIC_OBSERVER_v0.1.json"),
        "claim_boundary_sha256": _spec_sha("SCOUT_CONVEYOR_EVIDENCE_CLAIM_FIREWALL_v0.1.json"),
    }
    for key, val in expected.items():
        if key in params and params[key] != val:
            raise RuntimeError(f"generic Scout frozen resource mismatch: {key}")


def _rows_from_merged(merged: dict[str, Any]) -> tuple[list[dict[str, Any]], dict[str, set[str]], Counter[str], dict[str, set[str]]]:
    pars = {h: set(v) for h, v in merged["parents"].items()}
    wit = Counter({h: int(v) for h, v in merged["witness_count"].items()})
    src_child = {s: set(v) for s, v in merged["source_children"].items()}
    rows = []
    for h, raw in merged["children"].items():
        # Reuse the already-canonical repr generated by the composer.
        import ast
        rec = _canon(ast.literal_eval(raw))
        rows.append({"sha256": h, "record": rec, "parent_count_bounded": len(pars.get(h, set())), "witness_count": int(wit[h])})
    rows.sort(key=lambda x: x["sha256"])
    return rows, pars, wit, src_child


def exact_select_from_merged(merged: dict[str, Any], source_order: list[str], per_lane: int = PER_LANE) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    rows, pars, wit, src_child = _rows_from_merged(merged)
    if per_lane != PER_LANE:
        raise RuntimeError("conveyor scientific lane size is frozen at 256")
    N = min(per_lane, len(rows))
    row_by_sha = {x["sha256"]: x for x in rows}
    D, exact_meta = _farthest_exact(rows, N)
    B = sorted(rows, key=lambda x: (-x["parent_count_bounded"], -x["witness_count"], x["sha256"]))[:N]
    S = sorted(rows, key=lambda x: (len(set(x["record"][1])), max(Counter(x["record"][1]).values()), x["sha256"]))[:N]
    O = sorted(rows, key=lambda x: (-sum(v * (v - 1) // 2 for v in Counter(x["record"][1]).values()), -x["parent_count_bounded"], -x["witness_count"], x["sha256"]))[:N]
    line: list[dict[str, Any]] = []
    seen: set[str] = set()
    for ssha in source_order:
        hs = sorted(src_child.get(ssha, set()))
        if hs and len(line) < N and hs[0] not in seen:
            line.append(row_by_sha[hs[0]])
            seen.add(hs[0])
    for x in rows:
        if len(line) >= N:
            break
        if x["sha256"] not in seen:
            line.append(x)
            seen.add(x["sha256"])
    lanes = {"D": D, "B": B, "S": S, "O": O, "L": line}
    union = {x["sha256"]: x for lane in LANE_ORDER for x in lanes[lane]}
    selected = sorted(union.values(), key=lambda x: x["sha256"])
    selset = set(union)
    edges = sorted((s, h) for s in source_order for h in src_child.get(s, set()) if h in selset)
    pair = Counter()
    for s in source_order:
        hs = sorted(h for h in src_child.get(s, set()) if h in selset)
        for i in range(len(hs)):
            for j in range(i + 1, len(hs)):
                pair[(hs[i], hs[j])] += 1
    fib = Counter(tuple(sorted(pars[x["sha256"]])) for x in selected)
    br = {
        "selected_union": len(selected),
        "relation_edges": len(edges),
        "selected_multi_parent": sum(x["parent_count_bounded"] >= 2 for x in selected),
        "selected_max_parent_count": max((x["parent_count_bounded"] for x in selected), default=0),
        "shared_parent_pair_count": len(pair),
        "shared_parent_multiplicity_histogram": {str(k): v for k, v in sorted(Counter(pair.values()).items())},
        "distinct_exact_parent_fibers": len(fib),
        "selected_parent_histogram": {str(k): v for k, v in sorted(Counter(x["parent_count_bounded"] for x in selected).items())},
    }
    relation = {
        "selected": [
            {"sha256": x["sha256"], "record": repr(x["record"]), "bounded_parent_count": x["parent_count_bounded"], "witness_count": x["witness_count"]}
            for x in selected
        ],
        "edges": edges,
    }
    lane_seal = {
        "schema_id": "IG_SCOUT_GENERIC_SEALED_LANES_V0_1",
        "selection_rules_sha256": _spec_sha("SCOUT_CONVEYOR_SELECTION_RULES_v0.1.json"),
        "per_lane": N,
        "lane_order": LANE_ORDER,
        "lanes": {k: [x["sha256"] for x in lanes[k]] for k in LANE_ORDER},
        "selected_union": [x["sha256"] for x in selected],
        "selected_union_count": len(selected),
        "D_lane_exactness": exact_meta,
        "sealed_before_relation_analysis": True,
        "no_outcome_feedback": True,
    }
    wide = {
        "status": "SCOUT_COMPLETE",
        "evidence_label": "SCOUT_OBSERVED",
        "authority": "RECONNAISSANCE_ONLY",
        "population_complete": False,
        "generation": {
            "source_count": len(source_order),
            "attempts": int(merged["attempts"]),
            "lawful": int(merged["lawful"]),
            "unique_candidates": len(rows),
            "multi_parent_candidates": sum(len(v) >= 2 for v in pars.values()),
            "max_bounded_parent_count": max((len(v) for v in pars.values()), default=0),
        },
        "selection": {"per_lane": N, "union_selected": len(selected), "D_lane_exactness": exact_meta},
        "bounded_relation": br,
        "prohibitions": PROHIBITIONS,
    }
    return wide, relation, lane_seal


